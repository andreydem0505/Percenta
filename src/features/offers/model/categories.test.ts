import { describe, expect, it } from 'vitest';
import { isAllPurchases } from './categories';

describe('формулировки про все покупки', () => {
  it.each([
    'Все покупки',
    'За все покупки',
    'Все покупки на кассе',
    'Кэшбэк за все покупки',
    'На любые покупки',
    'Кешбек с любых покупок',
    'СО ВСЕХ ПОКУПОК',
    'На каждую покупку',
    'За любую покупку',
    'Кэшбэк на всё',
    '  НА   ВСЁ  ',
    'За всё остальное',
    'Во всех категориях',
    'В любых категориях',
    'Остальные покупки',
    'На прочие покупки',
    'Базовый кэшбэк',
    'Стандартный кешбек',
    'Кэшбэк везде',
    'Во всех магазинах',
    'All purchases',
  ])('выделяет «%s»', (category) => {
    expect(isAllPurchases(category)).toBe(true);
  });
  it.each([
    'Супермаркеты',
    'Все супермаркеты',
    'Всё для дома',
    'Все для ремонта',
    'Кафе и рестораны',
    'Все рестораны',
    'Любые аптеки',
    'Покупки в интернете',
    'На все авиабилеты',
    'Не на все покупки',
    'Не все покупки',
    'Не за любые покупки',
    '',
  ])('не выделяет отдельную категорию «%s»', (category) => {
    expect(isAllPurchases(category)).toBe(false);
  });
});
